"""Signed baseline (1.14.0): the lockfile's signature is checked once, when a gate is created, before anything is compared
against it. The cases are the shared golden file's baseline_cases, generated by the JS SDK; this SDK reproduces each one."""
import copy
import hashlib
import json
import os
import unittest
from unittest import mock

from crawlcheck import _ed25519
from crawlcheck.continuity import (CONTINUITY_DEFAULT_POLICY, CONTINUITY_FAILURE_CLASSES, new_operator_key, sign_lock,
                                   verify_lock_baseline)
from crawlcheck.continuity_gate import ContinuityGate, ContinuityRefused
from crawlcheck.mcp import McpPreflightRefused, with_preflight
from crawlcheck.verify import canon, key_policy_from
from tests.test_mcp import Session, cc, run

G = json.load(open(os.path.join(os.path.dirname(__file__), "fixtures", "continuity.json"), encoding="utf-8"))
URL = "https://mcp.example.com/mcp"
OP = G["operator"]


def B(n):
    return next(c for c in G["baseline_cases"] if c["name"] == n)


def _kw(o):
    m = {"operatorKeys": "operator_keys", "publishedKids": "published_kids", "trustedKids": "trusted_kids"}
    k = {m[a]: v for a, v in o.items() if a in m}
    if o.get("keyPolicyDirectory"):
        k["key_policy"] = key_policy_from(G["key_directory"])
    return k


class Golden(unittest.TestCase):
    def test_baseline_cases(self):
        for c in G["baseline_cases"]:
            with self.subTest(c["name"]):
                r = verify_lock_baseline(c["lock"], **_kw(c["opts"]))
                used = r.pop("lock")
                self.assertEqual(r, c["expect"])
                self.assertEqual(hashlib.sha256(canon(used).encode("utf-8")).hexdigest(), c["used_sha256"])

    def test_sign_lock_matches_js_byte_for_byte(self):
        self.assertEqual(sign_lock(G["lock"], OP["privateKey"]), OP["signed_lock"])
        self.assertEqual(sign_lock(G["lock"], bytes.fromhex(OP["seed_hex"])), OP["signed_lock"])

    def test_signing_matches_rfc8032_test_vector_1(self):
        seed = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
        self.assertEqual(_ed25519.public_key(seed).hex(), "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a")
        self.assertEqual(_ed25519.sign(seed, b"").hex(), "e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e065224901555fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b")

    def test_new_class(self):
        self.assertEqual(len(CONTINUITY_FAILURE_CLASSES), 14)
        self.assertEqual(CONTINUITY_DEFAULT_POLICY["effects"]["baseline_untrusted"], "deny")


class Gate(unittest.TestCase):
    def test_enforce_edited_after_signing_fails_at_construction(self):
        with self.assertRaises(ContinuityRefused) as e:
            ContinuityGate(B("edited_after_signing")["lock"], mode="enforce")
        self.assertEqual(e.exception.record["events"][0]["class"], "baseline_untrusted")
        with self.assertRaises(ContinuityRefused):
            ContinuityGate(B("forged_foreign_key")["lock"], mode="review")

    def test_observe_records_and_passes(self):
        recs = []
        g = ContinuityGate(B("edited_after_signing")["lock"], mode="observe", on_record=recs.append)
        self.assertEqual(g.baseline["trust"], "invalid")
        self.assertEqual([r["events"][0]["class"] for r in recs], ["baseline_untrusted"])
        self.assertEqual(recs[0]["outcome"], "proceed")
        self.assertEqual(g.check([])["baseline"]["trust"], "invalid")

    def test_verified_and_named_in_records(self):
        g = ContinuityGate(B("crawlcheck_signed")["lock"], mode="enforce")
        self.assertEqual(g.baseline["trust"], "verified")
        self.assertEqual(g.records, [])
        r = g.check([])
        self.assertEqual((r["baseline"]["trust"], r["baseline"]["per_part"]), ("verified", True))

    def test_parts_added_after_signing_are_not_used(self):
        g = ContinuityGate(B("parts_added_after_signing")["lock"], mode="enforce")
        self.assertEqual((g.baseline["trust"], g.baseline["parts_used"]), ("verified", False))
        self.assertFalse(g.check([])["baseline"]["per_part"])

    def test_unsigned_and_require_signed(self):
        self.assertEqual(ContinuityGate(G["lock"], mode="enforce").baseline["trust"], "unsigned")
        with self.assertRaisesRegex(ContinuityRefused, "unsigned and a signed one is required"):
            ContinuityGate(G["lock"], mode="enforce", require_signed_baseline=True)
        with self.assertRaisesRegex(ContinuityRefused, "unsigned"):
            ContinuityGate(G["lock"], mode="enforce", operator_keys=[OP["publicKey"]])
        ContinuityGate(G["lock"], mode="enforce", operator_keys=[OP["publicKey"]], require_signed_baseline=False)

    def test_operator_signed(self):
        g = ContinuityGate(OP["signed_lock"], mode="enforce", operator_keys=[OP["publicKey"]])
        self.assertEqual(g.baseline["trust"], "operator_signed")
        r = g.check(G["tools_v1"])
        self.assertEqual((r["outcome"], r["baseline"]["trust"]), ("proceed", "operator_signed"))
        with self.assertRaisesRegex(ContinuityRefused, "not one of the operator keys"):
            ContinuityGate(OP["signed_lock"], mode="enforce", operator_keys=[OP["other_publicKey"]])

    def test_attacker_edit_of_operator_baseline(self):
        L = copy.deepcopy(OP["signed_lock"]); L["tools"].append({"name": "export", "sha256": "e" * 64})
        with self.assertRaisesRegex(ContinuityRefused, "changed after the operator signed it"):
            ContinuityGate(L, mode="enforce", operator_keys=[OP["publicKey"]])
        del L["operator_signature"]
        with self.assertRaisesRegex(ContinuityRefused, "unsigned"):
            ContinuityGate(L, mode="enforce", operator_keys=[OP["publicKey"]])

    def test_verified_once_not_per_call(self):
        g = ContinuityGate(B("crawlcheck_signed")["lock"], mode="enforce")
        with mock.patch.object(_ed25519, "verify", side_effect=AssertionError("verified again")):
            for _ in range(3):
                g.check([])

    def test_new_key_round_trip(self):
        k = new_operator_key()
        s = sign_lock(G["lock"], k["private_key"])
        self.assertEqual(verify_lock_baseline(s, operator_keys=[k["public_key"]])["trust"], "operator_signed")
        self.assertEqual(s["operator_signature"]["kid"], k["kid"])


class Mcp(unittest.TestCase):
    def test_untrusted_baseline_refused_at_construction(self):
        s = Session(G["tools_v1"])
        with self.assertRaisesRegex(McpPreflightRefused, "baseline"):
            with_preflight(s, cc({"mcp.example.com": "allow"}), server_url=URL, lock=B("edited_after_signing")["lock"], tool_receipts="none", continuity={"mode": "enforce"})
        with self.assertRaisesRegex(McpPreflightRefused, "lockfile is not trusted"):
            with_preflight(s, cc({"mcp.example.com": "allow"}), server_url=URL, lock=B("forged_foreign_key")["lock"], tool_receipts="none")
        self.assertEqual(s.sent, [])

    def test_operator_signed_connects(self):
        s = Session(G["tools_v1"])
        w = with_preflight(s, cc({"mcp.example.com": "allow"}), server_url=URL, lock=OP["signed_lock"], tool_receipts="none",
                           continuity={"mode": "enforce", "operator_keys": [OP["publicKey"]]})
        run(w.initialize())
        self.assertEqual(w.preflight.baseline["trust"], "operator_signed")
        self.assertEqual(w.preflight.continuity["baseline"]["trust"], "operator_signed")


if __name__ == "__main__":
    unittest.main()
